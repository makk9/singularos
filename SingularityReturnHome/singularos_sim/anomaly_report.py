"""Anomaly report: what the onboard fault management hands the AI copilot.

Generated automatically by the controller at the recovery decision point,
from the same controller-side data the deterministic planner uses: alerts
raised, diagnostic results and how each was obtained, the navigation and
attitude estimates with their stated uncertainty and age, a short recent
trend, proximity to the dock and the station structure, fuel, and the raw
text of station messages. No truth, no fault labels, and no baseline
decision.

Values are numbers with units in the field names; a single header line
states the frame. The report is compact JSON so it stays short and the model
reads data rather than prose written for it.
"""

import json
import math

HEADER = ("ANOMALY REPORT, auto-generated by onboard fault management. SI units. "
          "Station frame: +x radial (away from Earth), +y along-track; dock port at (0, 0). "
          "Thruster health is the diagnosed fraction of nominal thrust.")


def _verdict(h, usable_threshold):
    if h < usable_threshold:
        return "FAILED"
    return "NOMINAL" if h >= 0.999 else f"DEGRADED {round(100 * h)}%"


def _alerts(events):
    out = []
    for e in events:
        t = round(e["t"], 1)
        if e["type"] == "anomaly_detected":
            out.append({"t_s": t, "level": "WARNING", "code": "PROPULSION_ANOMALY",
                        "detail": f"observed vs commanded delta-v mismatch {e['residual_m_s']:.3f} m/s"})
        elif e["type"] == "investigate_start":
            out.append({"t_s": t, "level": "CAUTION", "code": "FAULT_INVESTIGATION", "detail": "braking, then thruster tests"})
        elif e["type"] == "diagnostic_turn":
            out.append({"t_s": t, "level": "CAUTION", "code": "TEST_FIRING_TURN",
                        "detail": f"turned before testing {e['thruster']}: structure {e['distance_to_structure_m']} m away"})
        elif e["type"] == "orbital_triage":
            out.append({"t_s": t, "level": "WARNING", "code": "UNSAFE_ORBIT", "detail": "; ".join(e["reasons"])})
    return out


def build_report(t, events, health, verified, usable_threshold, nav, nav_sigma, nav_age_s, att, att_sigma,
                 trend, proximity, fuel_kg, fuel_sigma_kg, reserve_kg, advisories):
    """Return the report as a dict (see module docstring)."""
    methods = {"brake": "braking_response", "pulse": "test_firing", None: "untested"}
    speed = math.hypot(nav["vx_m_s"], nav["vy_m_s"])
    return {
        "met_s": round(t, 1),
        "alerts": _alerts(events),
        "diagnostics": [
            {"t_s": round(e["t"], 1), "thruster": e["thruster"], "method": methods[e.get("method")],
             "measured_pct": round(100 * max(0.0, e["measured_ratio"]))}
            for e in events if e["type"] == "diagnostic"
        ],
        "thrusters": {n: {"health_pct": round(100 * h), "status": _verdict(h, usable_threshold),
                          "verified_by": methods[verified[n]]} for n, h in health.items()},
        "nav": {"x_m": round(nav["x_m"], 2), "y_m": round(nav["y_m"], 2),
                "vx_m_s": round(nav["vx_m_s"], 3), "vy_m_s": round(nav["vy_m_s"], 3), "speed_m_s": round(speed, 3),
                "sigma_pos_m": nav_sigma[0], "sigma_vel_m_s": nav_sigma[1], "age_s": round(nav_age_s, 2)},
        "attitude": {"heading_deg": round(math.degrees(att["heading_rad"]), 1),
                     "rate_deg_s": round(math.degrees(att["angular_rate_rad_s"]), 2),
                     "sigma_heading_deg": round(math.degrees(att_sigma), 2)},
        "trend": trend,
        "proximity": proximity,
        "fuel": {"kg": round(fuel_kg, 3), "reserve_kg": reserve_kg, "sigma_kg": fuel_sigma_kg},
        "station_messages": [{"id": a["id"], "t_s": a["t_s"], "text": a["text"]} for a in advisories],
    }


PAIRS = (("forward", "backward"), ("left", "right"))


def key_facts(report):
    """One line of facts derived from the report itself (no extra information)."""
    th = report["thrusters"]
    failed = [n for n, v in th.items() if v["status"] == "FAILED"]
    degraded = [f"{n} {v['health_pct']}%" for n, v in th.items() if v["status"].startswith("DEGRADED")]
    pairs = [f"{a}/{b}" for a, b in PAIRS if th[a]["status"] != "FAILED" and th[b]["status"] != "FAILED"]
    p = report["proximity"]
    parts = [
        f"failed thrusters: {', '.join(failed) or 'none'}",
        f"degraded: {', '.join(degraded) or 'none'}",
        f"intact opposing pairs: {', '.join(pairs) or 'none'}",
        f"speed {report['nav']['speed_m_s']} m/s, {p['dock_range_m']} m from the dock",
        f"active station messages: {len(report['station_messages'])}",
    ]
    return "KEY FACTS: " + "; ".join(parts) + "."


def report_text(report):
    return (HEADER + "\n" + key_facts(report) + "\n" + json.dumps(report, separators=(",", ":"))
            + "\nPropose the recovery plan.")
